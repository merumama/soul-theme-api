-- ---------- テーブル ----------

-- 登録した人の一覧（approved = true の人だけが用語集を見られる）
create table if not exists public.glossary_members (
  user_id     uuid primary key references auth.users(id) on delete cascade,
  email       text not null,
  name        text not null default '',
  approved    boolean not null default false,
  memo        text not null default '',          -- 管理者用のメモ
  created_at  timestamptz not null default now(),
  approved_at timestamptz
);

-- 期（何期の受講生か）。登録時に本人が入力する
alter table public.glossary_members add column if not exists ki smallint check (ki between 1 and 999);

-- 用語
create table if not exists public.glossary_terms (
  id         bigint generated by default as identity primary key,
  term       text not null,                      -- 用語
  yomi       text not null default '',           -- 読み方（ひらがな。行タブの振り分けに使う）
  short      text not null default '',           -- 一言でいうと
  detail     text not null default '',           -- 詳しい意味
  example    text not null default '',           -- 具体例
  related    text not null default '',           -- 関連ワード（「、」区切り）
  updated_at timestamptz not null default now()
);

-- ---------- 関数 ----------

-- 承認済みのメンバーかどうか
create or replace function public.is_glossary_member()
returns boolean
language sql stable security definer set search_path = public
as $$
  select exists (select 1 from public.glossary_members where user_id = auth.uid() and approved);
$$;

-- 新規登録（名前・期の登録・変更）。approved はここでは絶対に変えない
drop function if exists public.glossary_register(text);
create or replace function public.glossary_register(p_name text, p_ki integer default null)
returns public.glossary_members
language plpgsql security definer set search_path = public
as $$
declare
  v_name text := left(trim(coalesce(p_name, '')), 60);
  v_row public.glossary_members;
begin
  if auth.uid() is null then
    raise exception 'not_signed_in';
  end if;
  if v_name = '' then
    raise exception 'name_required';
  end if;
  if p_ki is null or p_ki not between 1 and 999 then
    raise exception 'ki_required';
  end if;
  insert into public.glossary_members (user_id, email, name, ki)
  values (auth.uid(), lower(coalesce(auth.jwt() ->> 'email', '')), v_name, p_ki)
  on conflict (user_id) do update set name = excluded.name, ki = excluded.ki
  returning * into v_row;
  return v_row;
end;
$$;

-- 承認した日時を自動で記録 / 用語の更新日時を自動で記録
create or replace function public.glossary_members_stamp()
returns trigger
language plpgsql
as $$
begin
  if new.approved and (tg_op = 'INSERT' or not old.approved) then
    new.approved_at := now();
  elsif not new.approved then
    new.approved_at := null;
  end if;
  return new;
end;
$$;

drop trigger if exists glossary_members_stamp on public.glossary_members;
create trigger glossary_members_stamp
  before insert or update on public.glossary_members
  for each row execute function public.glossary_members_stamp();

create or replace function public.glossary_terms_stamp()
returns trigger
language plpgsql
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists glossary_terms_stamp on public.glossary_terms;
create trigger glossary_terms_stamp
  before update on public.glossary_terms
  for each row execute function public.glossary_terms_stamp();

-- ---------- 権限（RLS） ----------

alter table public.glossary_members enable row level security;
alter table public.glossary_terms   enable row level security;

revoke all on public.glossary_members, public.glossary_terms from anon, authenticated;
grant select on public.glossary_members, public.glossary_terms to authenticated;

revoke all on function public.glossary_register(text, integer) from public, anon;
revoke all on function public.is_glossary_member() from public, anon;
grant execute on function public.glossary_register(text, integer) to authenticated;
grant execute on function public.is_glossary_member() to authenticated;

-- 自分の登録状況だけ見られる
drop policy if exists glossary_members_select_own on public.glossary_members;
create policy glossary_members_select_own on public.glossary_members for select to authenticated
  using (user_id = auth.uid());

-- 用語は承認済みの人だけ読める（書き換えは管理画面からのみ）
drop policy if exists glossary_terms_select_member on public.glossary_terms;
create policy glossary_terms_select_member on public.glossary_terms for select to authenticated
  using (public.is_glossary_member());
